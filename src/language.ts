const LOOKUP = new Map<string, string>();
for (const [language, words] of Object.entries(LANGUAGE_WORDS)) {
  for (const word of words) LOOKUP.set(word, language);
}

/** Languages the guesser knows. */
export const KNOWN_LANGUAGES = Object.keys(LANGUAGE_WORDS);

/**
 * The language of `text`, or undefined when it can't be told: fewer than three known words, or no
 * language with at least twice the hits of the next one.
 */
export function guessLanguage(text: string): string | undefined {
  const counts = new Map<string, number>();
  for (const word of text.toLowerCase().match(/\p{L}+/gu) ?? []) {
    const language = LOOKUP.get(word);
    if (language !== undefined) counts.set(language, (counts.get(language) ?? 0) + 1);
  }
  const [first, second] = [...counts].sort((a, b) => b[1] - a[1]);
  if (first === undefined || first[1] < 3) return undefined;
  if (second !== undefined && first[1] < second[1] * 2) return undefined;
  return first[0];
}
